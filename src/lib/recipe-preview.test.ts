import test from 'node:test';
import assert from 'node:assert/strict';
import { inspectRecipePreview, previewTimeoutAction, previewReviewChannel, validPreviewReviewToken, recipePreviewReadyMessage,
  readRecipePreviewReady, recipePreviewUrl, type PreviewDocument, type RecipePreviewScope } from './recipe-preview';

const expected = { url: 'https://www.jesie.pl/pl/preview/recipe?revision=3', recipeId: 'recipe', revision: 3, locale: 'pl' };
const loaded: PreviewDocument = { url: expected.url, recipeId: 'recipe', revision: '3', locale: 'pl', hasContent: true };
const token = '2bf38c83-2155-42ea-a56e-d87f52efc290';
const otherToken = '52097461-ecb7-4269-9f26-f6b373314ea9';
const scope: RecipePreviewScope = { recipeId: 'recipe', revision: 3, token };

test('review tokens use the UUID v4 format generated by crypto.randomUUID', () => {
  assert.equal(validPreviewReviewToken(token), true);
  assert.equal(validPreviewReviewToken(token.toUpperCase()), true);
  for (const value of [undefined, null, 12, {}, '', 'token', ` ${token}`, `${token}\n`, token.replace('-42ea-', '-12ea-'), token.replace('-a56e-', '-756e-')]) {
    assert.equal(validPreviewReviewToken(value), false);
  }
  assert.equal(previewReviewChannel(token), `jesie:preview-review:v1:${token}`);
  assert.notEqual(previewReviewChannel(token), previewReviewChannel(otherToken));
});

test('ready messages retain the exact review scope and support both preview languages', () => {
  for (const locale of ['pl', 'en'] as const) {
    const message = recipePreviewReadyMessage(scope, locale);
    assert.deepEqual(message, { type: 'jesie:preview-ready:v1', ...scope, locale });
    assert.deepEqual(readRecipePreviewReady(message, scope), { locale, revision: 3 });
  }
});

test('foreign, stale and malformed ready messages cannot confirm a preview', () => {
  const ready = recipePreviewReadyMessage(scope, 'pl');
  for (const value of [null, undefined, false, 1, 'ready', [], {}, { ...ready, type: 'ready' }, { ...ready, recipeId: 'other' },
    { ...ready, revision: 2 }, { ...ready, revision: '3' }, { ...ready, revision: NaN }, { ...ready, token: otherToken },
    { ...ready, token: 'invalid' }, { ...ready, token: undefined }, { ...ready, locale: 'PL' }, { ...ready, locale: 'de' },
    { ...ready, locale: null }, { ...ready, locale: undefined }]) {
    assert.equal(readRecipePreviewReady(value, scope), null);
  }
  for (const expectedScope of [{ ...scope, recipeId: 'other' }, { ...scope, revision: 4 }, { ...scope, token: otherToken },
    { ...scope, token: 'invalid' }, { ...scope, recipeId: '' }, { ...scope, revision: 0 }, { ...scope, revision: 1.5 }, { ...scope, revision: Infinity }]) {
    assert.equal(readRecipePreviewReady(ready, expectedScope), null);
  }
});

test('preview URLs carry the same review token across languages and attempts, and rotate it for a new scope', () => {
  assert.equal(recipePreviewUrl('recipe', 3, 'pl'), '/pl/preview/recipe?revision=3');
  assert.equal(recipePreviewUrl('recipe', 3, 'pl', token, 0), `/pl/preview/recipe?revision=3&previewReview=${token}&previewAttempt=0`);
  assert.equal(recipePreviewUrl('recipe', 3, 'en', token, 1), `/en/preview/recipe?revision=3&previewReview=${token}&previewAttempt=1`);
  const next = new URL(recipePreviewUrl('recipe', 4, 'en', otherToken), 'https://www.jesie.pl');
  assert.equal(next.searchParams.get('previewReview'), otherToken);
  assert.equal(next.searchParams.get('revision'), '4');
  assert.equal(recipePreviewUrl('recipe/id ?#', 3, 'pl'), '/pl/preview/recipe%2Fid%20%3F%23?revision=3');
  for (const invalidToken of ['', 'invalid', `${token}&foreign=1`]) assert.equal(recipePreviewUrl('recipe', 3, 'pl', invalidToken, 1), '/pl/preview/recipe?revision=3&previewAttempt=1');
  for (const invalidAttempt of [-1, 1.5, NaN, Infinity]) assert.equal(recipePreviewUrl('recipe', 3, 'pl', token, invalidAttempt), `/pl/preview/recipe?revision=3&previewReview=${token}`);
});

test('the document inspector tolerates retry nonces but never a foreign review token', () => {
  const url = new URL(recipePreviewUrl('recipe', 3, 'pl', token, 0), 'https://www.jesie.pl').href;
  const document = { ...loaded, url };
  assert.equal(inspectRecipePreview(document, { ...expected, url: url.replace('previewAttempt=0', 'previewAttempt=1') }), 'ready');
  assert.equal(inspectRecipePreview(document, { ...expected, url: url.replace(token, otherToken) }), 'error');
});

test('the initial blank document never counts as a loaded recipe, even if a load event fires', () => {
  assert.equal(inspectRecipePreview({ ...loaded, url: 'about:blank' }, expected), 'pending');
  assert.equal(inspectRecipePreview({ ...loaded, url: '' }, expected), 'pending');
});

test('ready requires the exact private URL, current revision, language, marker, and content', () => {
  assert.equal(inspectRecipePreview(loaded, expected), 'ready');
  for (const changed of [{ url: 'https://www.jesie.pl/admin/login' }, { url: 'https://www.jesie.pl/pl/preview/recipe?revision=2' },
    { recipeId: 'another-recipe' }, { revision: '2' }, { locale: 'en' }, { recipeId: null }, { hasContent: false }]) {
    assert.equal(inspectRecipePreview({ ...loaded, ...changed }, expected), 'error');
  }
  assert.equal(inspectRecipePreview(loaded, { ...expected, locale: 'en', url: 'https://www.jesie.pl/en/preview/recipe?revision=3' }), 'error', 'an earlier language cannot mark the new frame ready');
});

test('a blank initial navigation gets at most one automatic retry; further attempts require a click', () => {
  assert.equal(previewTimeoutAction(0), 'retry');
  for (const attempt of [1, 2, 3, 20]) assert.equal(previewTimeoutAction(attempt), 'error');
});

test('only the read-only previewAttempt nonce is ignored when confirming the loaded document', () => {
  const retried = { ...expected, url: `${expected.url}&previewAttempt=1` };
  assert.equal(inspectRecipePreview(loaded, retried), 'ready', 'the same correct document remains valid during retry');
  assert.equal(inspectRecipePreview({ ...loaded, url: `${loaded.url}&previewAttempt=0` }, retried), 'ready');
  assert.equal(inspectRecipePreview({ ...loaded, url: `${loaded.url}&previewAttempt=99` }, expected), 'ready');
  for (const url of [`${loaded.url}&other=1`, `${loaded.url}&previewAttemptExtra=1`, 'https://other.example/pl/preview/recipe?revision=3&previewAttempt=1',
    'https://www.jesie.pl/pl/preview/another?revision=3&previewAttempt=1', 'https://www.jesie.pl/pl/preview/recipe?revision=2&previewAttempt=1', 'invalid-url']) {
    assert.equal(inspectRecipePreview({ ...loaded, url }, retried), 'error');
  }
});
